// Route registry generator — derives the plugin's route list from the actual
// dispatch code in Editor/MCPBridgeServer.cs and writes it to
// Editor/MCPBridgeServer.Routes.g.cs (a partial-class file owned by this script).
//
// The old hand-maintained list in GetRegisteredRoutes() drifted badly (~150 of
// ~320 routes, several wrong names) which silently broke dynamic tool discovery.
// A generated set can't drift: CI runs `node tools~/generate-routes.mjs --check`
// and fails the build when the .g.cs no longer matches the switch.
//
// Usage:
//   node tools~/generate-routes.mjs          # regenerate the .g.cs file
//   node tools~/generate-routes.mjs --check  # exit 1 if the file is out of date

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "Editor", "MCPBridgeServer.cs");
const TARGET = join(ROOT, "Editor", "MCPBridgeServer.Routes.g.cs");

const source = readFileSync(SOURCE, "utf8");

// ── Extract case labels from the RouteRequest switch ──
const routeRequestStart = source.indexOf("private static object RouteRequest");
if (routeRequestStart < 0) throw new Error("RouteRequest method not found — did MCPBridgeServer.cs change shape?");
const routeRequestEnd = source.indexOf("\n                default:", routeRequestStart);
if (routeRequestEnd < 0) throw new Error("RouteRequest default case not found");
const switchBody = source.slice(routeRequestStart, routeRequestEnd);

const routes = new Set();
for (const match of switchBody.matchAll(/^\s*case "([^"]+)":/gm)) {
  routes.add(match[1]);
}

// ── Routes dispatched before/outside the switch ──
routes.add("_meta/routes");

// ── Deferred routes (async-callback dictionary in the class header) ──
// Match from the field name to the first initializer brace: the nested generic type
// contains no braces, so the first "{" after "_deferredRoutes" opens the initializer.
// (A "<[^>]+>>" type matcher cannot span Dictionary<string, Action<...>>> — it dies
// on the first ">" — and silently captured nothing.)
const deferredBlockMatch = source.match(/_deferredRoutes[^{]*\{([\s\S]*?)\};/);
if (!deferredBlockMatch) {
  throw new Error("_deferredRoutes initializer not found — parser assumptions broke.");
}
let deferredCount = 0;
for (const match of deferredBlockMatch[1].matchAll(/\{\s*"([^"]+)"\s*,/g)) {
  routes.add(match[1]);
  deferredCount++;
}
if (deferredCount === 0) {
  throw new Error("No deferred routes extracted — parser assumptions broke.");
}

// Note: routes behind conditional compilation (e.g. uma/* under #if UMA_INSTALLED)
// are always listed — source-text generation can't evaluate defines. On projects
// without the optional package those routes pass the 404 gate and fall through to
// the dispatch default's "Unknown API endpoint" error, same as before this registry.

if (routes.size < 200) {
  throw new Error(`Only ${routes.size} routes extracted — parser likely broke; refusing to emit a shrunken registry.`);
}

const sorted = [...routes].sort();
const lines = sorted.map((r) => `            "${r}",`).join("\n");

const content = `// <auto-generated/>
// Generated by tools~/generate-routes.mjs from the RouteRequest dispatch in
// MCPBridgeServer.cs — DO NOT EDIT BY HAND. Regenerate after adding a route:
//   node tools~/generate-routes.mjs
// CI runs --check mode and fails when this file is out of date.
using System.Collections.Generic;

namespace UnityMCP.Editor
{
    public static partial class MCPBridgeServer
    {
        /// <summary>Every route the bridge can dispatch (${sorted.length} routes).</summary>
        internal static readonly string[] GeneratedRoutes = new string[]
        {
${lines}
        };

        /// <summary>Fast membership lookup used for unknown-route 404s.</summary>
        internal static readonly HashSet<string> KnownRoutes = new HashSet<string>(GeneratedRoutes);
    }
}
`;

const checkMode = process.argv.includes("--check");
let existing = null;
try {
  existing = readFileSync(TARGET, "utf8");
} catch {
  // Target doesn't exist yet.
}

if (checkMode) {
  if (existing === content) {
    console.log(`Route registry up to date (${sorted.length} routes).`);
    process.exit(0);
  }
  console.error("Route registry is OUT OF DATE. Run: node tools~/generate-routes.mjs");
  process.exit(1);
}

writeFileSync(TARGET, content, "utf8");
console.log(`Wrote ${TARGET} with ${sorted.length} routes.`);
